"""Human-readable Markdown report rendered from the analysis dictionary.

The report is a pure function of ``analysis.json``, so it can be regenerated
from the published JSON without the traces.
"""

from __future__ import annotations

from typing import Any, Mapping

from binding_gate.stats import prereg
from binding_gate.stats.metrics import arm_key, comparison_key


def _pct(value: float | None) -> str:
    return "n/a" if value is None else f"{100 * value:.1f}%"


def _pp(value: float | None) -> str:
    """A difference of two shares, in percentage points."""
    return "n/a" if value is None else f"{100 * value:+.1f} pp"


def _ci(ci: Mapping[str, Any] | None, fmt=_pct) -> str:
    if not ci or ci.get("low") is None:
        return "n/a"
    text = f"[{fmt(ci['low'])}, {fmt(ci['high'])}]"
    return text + (f" ({ci['undefined']} undef.)" if ci.get("undefined") else "")


def _est(model: Mapping[str, Any], key: str, fmt=_pct, with_ci: bool = True) -> str:
    entry = model["estimates"].get(key)
    if entry is None:
        return "-"
    return fmt(entry["value"]) + (f" {_ci(entry['ci'], fmt)}" if with_ci else "")


def render_markdown(analysis: Mapping[str, Any], *, figure_note: str = "") -> str:
    level = float(prereg.CI_LEVEL)
    params = analysis["parameters"]
    lines: list[str] = [
        f"# Analysis report: {analysis['dataset']} (layer {analysis['layer']}), split `{analysis['split']}`",
        "",
        "Generated by `binding_gate.stats` from trace files only; no model was called. "
        "Thresholds and bootstrap parameters are the PROPOSED values of PREREGISTRATION.md "
        "sections 8 and 11 (they require owner approval before freeze).",
        "",
        f"- Bootstrap: {params['used']['bootstrap_resamples']:,} cluster resamples of `group_id`, seed "
        f"{params['used']['bootstrap_seed']}, {level:.0%} percentile intervals"
        + ("" if params["as_preregistered"] else " **(differs from the pre-registration)**"),
        f"- Correct outcome(s): {', '.join(params['correct_outcomes'])}"
        + (" **(layer-3 placeholder)**" if params.get("correct_rule_is_placeholder") else ""),
        f"- Run directories: {', '.join(analysis['inputs']['run_dirs']) or '(records given directly)'}",
        f"- Records: {analysis['inputs']['n_records']:,}",
    ]
    for run in analysis["inputs"]["runs"]:
        lines.append(
            f"  - run `{run['run_id']}`: commit `{run['git_commit'][:12]}`, config `{run['config_hash'][:12]}`, "
            f"tag `{run['test_unlock_tag']}`, {'finished' if run['finished'] else 'UNFINISHED'}"
        )
    rule = analysis.get("outcome_rule")  # PR 16: layers 2 and 3 name their rule (absent for layer 1)
    if rule:
        lines.append(f"- Outcome rule: scorer `{rule['scorer']}`; decision: {rule['decision']}")
    if analysis["confirmatory_blockers"]:
        lines += ["", "**Not confirmatory:** " + "; ".join(analysis["confirmatory_blockers"])]
    if figure_note:
        lines += ["", f"Figures: {figure_note}"]

    lines += ["", "## Hypotheses (per model)", "", "| model | H1 | H2 | H3 | H4 | controlled-layer claim |", "|---|---|---|---|---|---|"]
    for name, model in analysis["models"].items():
        cells = []
        for h in ("H1", "H2", "H3", "H4"):
            result = model["hypotheses"][h]
            mark = "" if result["status"] == "NOT EVALUABLE" or result["confirmatory"] else " (not confirmatory)"
            cells.append(result["status"] + mark)
        lines.append(f"| {name} | " + " | ".join(cells) + f" | {model['controlled_layer_claim']} |")
    lines.append("")
    for h, entry in analysis["summary"].items():
        if entry["evaluated"]:
            lines.append(
                f"- {h}: supported for {len(entry['supported'])} of {len(entry['evaluated'])} model(s) "
                f"({len(entry['supported_confirmatory'])} confirmatory)"
                + (f"; trade-off for {len(entry['trade_off'])}" if entry["trade_off"] else "")
            )

    for name, model in analysis["models"].items():
        ref = model["reference"]
        lines += [
            "",
            f"## Model `{name}`",
            "",
            f"{model['n_groups']} groups (clusters), {model['n_items']} items, repeats {model['repeats']}, "
            f"{model['n_records']:,} records; complete: {'yes' if model['complete'] else '**no**'}"
            + (f" ({model['unpaired_records']} unpaired records)" if model["unpaired_records"] else ""),
            "",
            f"### Primary pair (always together), {level:.0%} cluster-bootstrap intervals",
            "",
            "| arm | M1 wrong among answered | M2 correct answers blocked | wrong / all | target-grounded / all "
            "| unparseable+error / all | abstained / all |",
            "|---|---|---|---|---|---|---|",
        ]
        for arm in model["arms"]:
            lines.append(
                f"| {arm} | {_est(model, arm_key(arm, 'm1'))} | "
                f"{_est(model, arm_key(arm, 'm2')) if arm != ref else '(reference)'} | "
                f"{_est(model, arm_key(arm, 'wrong_all'))} | {_est(model, arm_key(arm, 'correct_all'))} | "
                f"{_est(model, arm_key(arm, 'failed_all'), with_ci=False)} | "
                f"{_est(model, arm_key(arm, 'abstained_all'), with_ci=False)} |"
            )
        if ref:
            lines += [
                "",
                f"### Paired comparisons with `{ref}` (same items, model and repeats)",
                "",
                "| arm | M1 difference | relative reduction of M1 | wrong / all difference | "
                "worst-case M1 difference (6.4 item 7) |",
                "|---|---|---|---|---|",
            ]
            for arm in model["arms"]:
                if arm == ref:
                    continue
                lines.append(
                    f"| {arm} | {_est(model, comparison_key(arm, ref, 'diff_m1'), _pp)} | "
                    f"{_est(model, comparison_key(arm, ref, 'relred_m1'))} | "
                    f"{_est(model, comparison_key(arm, ref, 'diff_wrong_all'), _pp)} | "
                    f"{_est(model, comparison_key(arm, ref, 'diff_m1_worst'), _pp)} |"
                )
        lines += ["", "### Hypothesis details", ""]
        for h, result in model["hypotheses"].items():
            lines.append(f"- **{h}: {result['status']}**" + ("" if result["confirmatory"] else " (not confirmatory)"))
            for criterion in result["criteria"]:
                lines.append(
                    f"  - {'PASS' if criterion['passed'] else 'FAIL'} `{criterion['name']}`: "
                    f"{criterion['rule']}; observed {criterion['observed']}"
                )
            for note in result["notes"]:
                lines.append(f"  - note: {note}")
            for reason in result["non_confirmatory_reasons"]:
                lines.append(f"  - not confirmatory: {reason}")
            if result.get("sensitivity"):
                lines.append(
                    f"  - sensitivity bound: status under the worst case = "
                    f"{result['sensitivity']['status_under_worst_case']}"
                )

        lines += ["", "### Outcome table (all records, section 6.3)", ""]
        outcomes = list(next(iter(model["outcome_counts"].values())).keys())
        lines += ["| arm | " + " | ".join(outcomes) + " |", "|---|" + "---|" * len(outcomes)]
        for arm, counts in model["outcome_counts"].items():
            lines.append(f"| {arm} | " + " | ".join(str(counts[o]) for o in outcomes) + " |")

        lines += [
            "",
            "### By condition (exploratory): wrong-entity / all records",
            "",
            "| condition | " + " | ".join(model["arms"]) + " |",
            "|---|" + "---|" * len(model["arms"]),
        ]
        for condition, per_arm in model["conditions"].items():
            lines.append(
                f"| {condition} | " + " | ".join(_pct(per_arm[a]["wrong_all"]) for a in model["arms"]) + " |"
            )
        if ref and len(model["arms"]) > 1:
            others = [a for a in model["arms"] if a != ref]
            lines += [
                "",
                "### By condition (exploratory): M2 correct answers blocked",
                "",
                "| condition | " + " | ".join(others) + " |",
                "|---|" + "---|" * len(others),
            ]
            for condition, per_arm in model["conditions"].items():
                lines.append(f"| {condition} | " + " | ".join(_pct(per_arm[a]["m2"]) for a in others) + " |")
        for factor, levels in model["factors"].items():
            lines += [
                "",
                f"### By factor `{factor}` (exploratory): wrong / all, M1",
                "",
                "| level | " + " | ".join(model["arms"]) + " |",
                "|---|" + "---|" * len(model["arms"]),
            ]
            for level_name, per_arm in levels.items():
                lines.append(
                    f"| {level_name} | "
                    + " | ".join(f"{_pct(per_arm[a]['wrong_all'])}, M1 {_pct(per_arm[a]['m1'])}" for a in model["arms"])
                    + " |"
                )

        lines += ["", "### Spread across repeats (wrong / all)", "", "| arm | per repeat | min | max |", "|---|---|---|---|"]
        for arm, stats in model["repeat_spread"].items():
            entry = stats["wrong_all"]
            per = ", ".join(f"r{r}: {_pct(v)}" for r, v in entry["per_repeat"].items())
            lines.append(f"| {arm} | {per} | {_pct(entry['min'])} | {_pct(entry['max'])} |")

        lines += ["", "### Cost (model calls and reported tokens)", "", "| arm | paid calls | cached | failed | input tokens | output tokens |", "|---|---|---|---|---|---|"]
        for arm, cost in model["cost"].items():
            lines.append(
                f"| {arm} | {cost.get('paid_calls', 0)} | {cost.get('cached_calls', 0)} | {cost.get('failed_calls', 0)} | "
                f"{cost.get('input_tokens', 0):,} | {cost.get('output_tokens', 0):,} |"
            )

    pooled = analysis.get("pooled_descriptive") or {}
    if pooled.get("arms"):
        lines += ["", "## Pooled over models (descriptive only)", "", "| arm | M1 | M2 | wrong / all | target-grounded / all |", "|---|---|---|---|---|"]
        for arm, values in pooled["arms"].items():
            lines.append(
                f"| {arm} | {_pct(values['m1'])} | {_pct(values['m2'])} | {_pct(values['wrong_all'])} | "
                f"{_pct(values['correct_all'])} |"
            )
    lines += [
        "",
        "Per-condition tables, ablations and pooled numbers are exploratory (layer 2 decides H1 and H2 since PR 17). "
        "M4 (recovery after re-search) is reported in `analysis.json` and is a placeholder until PR 8.",
        "",
    ]
    return "\n".join(lines)
